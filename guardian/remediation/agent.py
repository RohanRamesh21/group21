"""The Fixer agent and the Fix Skeptic (Day 2). Both are read-only (constitution C6): no shell, no network, no write, no approve, no apply.

The Fixer chooses among candidates generated by guardian.scoring.contextual.fixrank; every proposal passes the referee
(`Remediator.propose`). The Skeptic runs in a FRESH context: it sees the sealed plan and the evidence, never the Fixer's reasoning.
A human decides (service.Remediator.decide). If no LLM is available, `run_fixer` falls back to the rule-based recommender and says so.
"""
from __future__ import annotations

import json

from guardian.agents.agents import Agent
from guardian.agents.tools import _s, _schema
from guardian.remediation import challenges, referee
from guardian.remediation.service import Remediator

ALL = {"fixer", "fix_skeptic"}


class _Board:
    """Just enough of the investigation Board for Agent: an audit logger."""

    def __init__(self, rem: Remediator):
        self.rem = rem

    def log(self, **kw) -> None:
        self.rem.store.log(kw.pop("event", "board"), **kw)


class RemediationTools:
    """Same interface as agents.tools.ToolRegistry (schemas_for / call) with the remediation allow-lists."""

    def __init__(self, rem: Remediator):
        self.rem, self.board, self.specs = rem, _Board(rem), {}
        self.pace = 0.0
        self._register()

    def _add(self, name: str, desc: str, props: dict, agents, fn) -> None:
        self.specs[name] = {"desc": desc, "schema": _schema(props), "agents": set(agents), "fn": fn}

    def _register(self) -> None:
        S, nul = _s, ["string", "null"]
        self._add("list_priority_findings", "Top-N scored findings that have fix candidates (id, level, score, hard-signal flag, reachability, confidence).",
                  {"n": S("integer")}, ["fixer"], self._list)
        self._add("get_finding", "Score card of one finding. Returns an evidence_id you can cite.", {"finding_id": S("string")}, ["fixer"], self._get_finding)
        self._add("list_fix_candidates", "The deterministic fix candidates for one finding (the ONLY fixes you may propose). Returns an evidence_id.",
                  {"finding_id": S("string")}, ["fixer"], self._cands)
        self._add("check_upgrade_safety", "Predicted breaking-change risk of one candidate (semver jump, engines, peers, removed exports, install scripts, new advisories). Returns an evidence_id.",
                  {"finding_id": S("string"), "type": S("string"), "target": S(nul)}, ["fixer"], self._safety)
        self._add("propose_fix", "Propose exactly one generated candidate for a finding. The referee rejects anything else. Rationale: your own words, max 600 chars.",
                  {"finding_id": S("string"), "type": S("string"), "target": S(nul), "rationale": S("string"), "evidence_ids": S("array", items={"type": "string"})},
                  ["fixer"], self._propose)
        self._add("request_approval", "Queue a plan for the human decision. This does NOT approve anything.", {"plan_id": S("string")}, ["fixer"], self._request)
        self._add("answer_review", "Answer the Skeptic's concerns about your plan (max 600 chars, cite evidence ids). You cannot change a sealed plan.",
                  {"plan_id": S("string"), "answer": S("string"), "evidence_ids": S("array", items={"type": "string"})}, ["fixer"], self._answer)
        self._add("get_plan", "The sealed fix plan, its patch preview, forecast, upgrade safety and the deterministic checks already run.",
                  {"plan_id": S("string")}, ["fix_skeptic", "fixer"], self._get_plan)
        self._add("get_evidence", "Content of an evidence record by id.", {"evidence_id": S("string")}, ["fix_skeptic", "fixer"], self._evidence)
        self._add("submit_review", "Submit your review of a plan: accept, or concerns (each backed by evidence ids). You cannot approve or reject.",
                  {"plan_id": S("string"), "outcome": S("string", enum=["accept", "concerns"]), "concerns": S("array", items={"type": "string"}),
                   "evidence_ids": S("array", items={"type": "string"})}, ["fix_skeptic"], self._review)

    # ---- tools --------------------------------------------------------------
    def _list(self, agent: str, a: dict) -> str:
        return json.dumps(self.rem.ctx.priority(max(1, min(int(a["n"]), 20)), {fid for p in self.rem.store.plans() for fid in p.finding_ids}), indent=1)

    def _get_finding(self, agent: str, a: dict) -> str:
        eid = self.rem.evidence_finding(a["finding_id"])
        return f"evidence_id: {eid}\n{self.rem.store.evidence.content(eid)}"

    def _cands(self, agent: str, a: dict) -> str:
        if self.rem.ctx.finding(a["finding_id"]) is None:
            return "REJECTED: unknown finding id"
        eid = self.rem.evidence_candidates(a["finding_id"])
        return f"evidence_id: {eid}\n{self.rem.store.evidence.content(eid)}"

    def _safety(self, agent: str, a: dict) -> str:
        f = self.rem.ctx.finding(a["finding_id"])
        c = next((x for x in self.rem.ctx.cands(a["finding_id"]) if x["type"] == a["type"] and x.get("target") == a["target"]), None)
        if f is None or c is None:
            return "REJECTED: not a generated candidate of this finding"
        s = self.rem.safety_for(f, c)
        eid = self.rem.evidence_safety(a["finding_id"], c["id"], s)
        return f"evidence_id: {eid}\n{json.dumps(s, indent=1)}"

    def _propose(self, agent: str, a: dict) -> str:
        try:
            plan = self.rem.propose(a["finding_id"], a["type"], a["target"], a["rationale"], a["evidence_ids"], "fixer_agent")
        except referee.RefereeError as e:
            return f"REJECTED: {e}"
        self.rem.store.log("message", sender="fixer", recipient="skeptic", kind="hypothesis", plan=plan.id, claim=plan.rationale, evidence_ids=plan.evidence_ids)
        return (f"ACCEPTED {plan.id} (hash {plan.plan_sha256[:12]}); deterministic review: {plan.review.outcome}; this is a FORECAST, not verified. "
                "A human decides; you cannot approve or apply.")

    def _request(self, agent: str, a: dict) -> str:
        p = self.rem.store.get_plan(a["plan_id"])
        if p is None:
            return "REJECTED: unknown plan"
        self.rem.store.log("approval_requested", plan=p.id)
        return f"{p.id} is queued for the human decision (status stays '{p.status}')."

    def _answer(self, agent: str, a: dict) -> str:
        p = self.rem.store.get_plan(a["plan_id"])
        if p is None:
            return "REJECTED: unknown plan"
        try:
            referee.check_claim(a["answer"], a["evidence_ids"], self.rem.store.evidence)
        except referee.RefereeError as e:
            return f"REJECTED: {e}"
        p.review.exchange.append({"from": "fixer", "kind": "answer", "text": a["answer"], "evidence_ids": a["evidence_ids"]})
        self.rem.store.save_plan(p)  # review is outside the plan hash: the sealed action is unchanged
        self.rem.store.log("message", sender="fixer", recipient="skeptic", kind="answer", plan=p.id, claim=a["answer"], evidence_ids=a["evidence_ids"])
        return "ANSWER recorded"

    def _get_plan(self, agent: str, a: dict) -> str:
        p = self.rem.store.get_plan(a["plan_id"])
        if p is None:
            return "unknown plan"
        d = p.model_dump(include={"id", "finding_ids", "type", "target", "rationale", "evidence_ids", "forecast", "upgrade_safety", "confidence",
                                  "alternatives", "finding_summary", "produced_by"})
        d["patch_diff"], d["patch_supported"], d["deterministic_checks"] = p.patch.diff, p.patch.supported, p.review.checks
        return json.dumps(d, indent=1, default=str)

    def _evidence(self, agent: str, a: dict) -> str:
        ev = self.rem.store.evidence
        return f"evidence_id: {a['evidence_id']}\n{ev.content(a['evidence_id'])}" if ev.exists(a["evidence_id"]) else "unknown evidence id"

    def _review(self, agent: str, a: dict) -> str:
        p = self.rem.store.get_plan(a["plan_id"])
        if p is None:
            return "REJECTED: unknown plan"
        if a["outcome"] == "concerns":
            if not a["concerns"]:
                return "REJECTED: outcome 'concerns' needs at least one concern"
            try:
                referee.check_claim(" ".join(a["concerns"])[:600], a["evidence_ids"], self.rem.store.evidence)
            except referee.RefereeError as e:
                return f"REJECTED: {e}"
        r = p.review
        r.llm_outcome, r.llm_concerns, r.llm_evidence_ids = a["outcome"], [c[:300] for c in a["concerns"]], a["evidence_ids"]
        r.exchange.append({"from": "skeptic", "kind": "challenge" if a["outcome"] == "concerns" else "corroborate",
                           "text": "; ".join(r.llm_concerns) or "no concern found in the evidence", "evidence_ids": a["evidence_ids"]})
        # the LLM can only RAISE the outcome: a failed deterministic check can never be softened (C2-style floor for plans)
        det = challenges.outcome(r.checks)
        r.outcome = "block" if det == "block" else ("concerns" if (det == "concerns" or a["outcome"] == "concerns") else "accept")  # type: ignore[assignment]
        self.rem.store.save_plan(p)
        self.rem.store.log("message", sender="skeptic", recipient="fixer", kind=r.exchange[-1]["kind"], plan=p.id, claim=r.exchange[-1]["text"], evidence_ids=a["evidence_ids"])
        return f"REVIEW recorded: {a['outcome']}"

    # ---- registry interface ---------------------------------------------------
    def schemas_for(self, agent: str) -> list[dict]:
        return [{"name": n, "description": s["desc"], "input_schema": s["schema"], "strict": True} for n, s in self.specs.items() if agent in s["agents"]]

    def call(self, agent: str, name: str, args: dict, ctx: dict | None = None) -> str:
        spec = self.specs.get(name)
        if spec is None or agent not in spec["agents"]:
            self.rem.store.log("denied_tool", agent=agent, tool=name)
            return f"DENIED: tool '{name}' is not on the {agent} allow-list (C6)"
        self.rem.store.log("tool_call", agent=agent, tool=name, args={k: (v if len(json.dumps(v, default=str)) < 300 else "...") for k, v in args.items()})
        try:
            return spec["fn"](agent, args)
        except Exception as e:  # tool errors go back to the agent, not up the stack
            return f"TOOL ERROR: {type(e).__name__}: {e}"


def run_fixer(rem: Remediator, backend, top_n: int = 3, rounds: int = 1) -> list:
    """Fixer proposes, Skeptic (fresh context) reviews High/Critical and hard-signal plans, Fixer answers up to `rounds` times (max 2)."""
    rounds = max(0, min(rounds, 2))
    tools = RemediationTools(rem)
    before = {p.id for p in rem.store.plans()}
    fixer = Agent("fixer", backend, tools, max_steps=8 + 8 * top_n)
    rem.store.log("agent_start", agent="fixer", top_n=top_n)
    fixer.run(f"Recommend one fix for each of the top {top_n} priority findings that still need one. Start with list_priority_findings(n={top_n}).")
    new = [p for p in rem.store.plans() if p.id not in before]
    for p in new:
        if p.finding_summary.get("level") in ("high", "critical") or p.finding_summary.get("floor"):
            for rnd in range(rounds + 1):
                skeptic = Agent("fix_skeptic", backend, tools, max_steps=10)  # fresh context every round: never sees the Fixer's reasoning
                skeptic.run(f"Review fix plan {p.id}. Start with get_plan. Round {rnd + 1}.")
                cur = rem.store.get_plan(p.id)
                if cur is None or cur.review.llm_outcome != "concerns" or rnd == rounds:
                    break
                fixer.run(f"The Skeptic raised concerns about {p.id}: {'; '.join(cur.review.llm_concerns)[:500]}. Answer with answer_review (evidence ids required), "
                          "or say so if the concern is right. You cannot change the sealed plan.")
    return [rem.store.get_plan(p.id) for p in new]
