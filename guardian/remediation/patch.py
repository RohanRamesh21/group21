"""Patch preview: turn a fix candidate into the exact file changes, WITHOUT writing anywhere.

`preview()` is a pure function of (candidate, finding, project tree, optional base tree). apply.py later writes the same
`files` into a throwaway copy. The lockfile is not previewed: it is regenerated by `npm install --package-lock-only
--ignore-scripts` (a fetch step) when the plan is applied, and the preview says so.

Supported in v1: upgrade_to_fixed, override_transitive, remove_package, revert_change (package or file).
Recommend-only in v1: pin_action_sha, pin_image_digest (need a networked tag->SHA / digest lookup), escalate (no change).
"""
from __future__ import annotations

import difflib
import json
import re
from pathlib import Path

from guardian.remediation.models import PatchPreview

DEP_SECTIONS = ("dependencies", "devDependencies", "optionalDependencies")
SIMPLE_SPEC = re.compile(r"^([\^~]|>=|=)?(\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.+-]*)?)$")
NAME_VER = re.compile(r"^(?:pkg:npm/)?(@?[^@\s]+)@([^@\s]+)$")


class PatchError(ValueError):
    pass


def _unified(path: str, old: str, new: str) -> str:
    return "".join(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True), fromfile=f"a/{path}", tofile=f"b/{path}"))


def _indent(text: str) -> int | str:
    m = re.search(r"^([ \t]+)\S", text, re.M)
    return (m.group(1) if "\t" in m.group(1) else len(m.group(1))) if m else 2


def _dump(data: dict, like: str) -> str:
    out = json.dumps(data, indent=_indent(like), ensure_ascii=False)
    return out + ("\n" if like.endswith("\n") else "")


def _package_name(finding: dict) -> str | None:
    p = finding.get("package") or {}
    if p.get("name"):
        return p["name"]
    m = NAME_VER.match((finding.get("component") or "").strip())
    return m.group(1) if m else None


def _read(tree: Path, rel: str) -> str | None:
    p = tree / rel
    return p.read_text(encoding="utf-8") if p.is_file() else None


def _sections_with(data: dict, name: str) -> list[str]:
    return [s for s in DEP_SECTIONS if name in (data.get(s) or {})]


def _manifest_preview(old: str, new: str, notes: list[str], lossless_check: bool = True) -> PatchPreview:
    return PatchPreview(supported=True, diff=_unified("package.json", old, new), files={"package.json": new}, lockfile="regenerate", notes=notes)


def _roundtrip_note(old: str, data: dict, notes: list[str]) -> None:
    if _dump(data, old) != old:
        notes.append("package.json is not in canonical JSON layout: the preview rewrites its formatting (content changes are listed in the diff)")


def _upgrade(name: str, target: str, old: str, data: dict) -> PatchPreview:
    secs = _sections_with(data, name)
    if not secs:
        return PatchPreview(supported=False, notes=[f"{name} is not declared in package.json (transitive, workspace or another manifest): "
                                                    "a direct upgrade cannot be expressed here"])
    new_data = json.loads(json.dumps(data))
    notes: list[str] = []
    for s in secs:
        spec = new_data[s][name]
        m = SIMPLE_SPEC.match(spec)
        if not m:
            return PatchPreview(supported=False, notes=[f"{name} is declared as '{spec}' in {s}: only plain version ranges can be rewritten automatically"])
        prefix = m.group(1) or ""
        new_data[s][name] = f"{prefix}{target}"
        notes.append(f"{s}: {name} '{spec}' -> '{prefix}{target}' (range prefix '{prefix or 'exact'}' kept; the spec is bumped because "
                     "a lockfile re-resolution would otherwise keep the old locked version)")
    _roundtrip_note(old, data, notes)
    notes.append("package-lock.json will be regenerated when the plan is applied (not shown in this preview)")
    return _manifest_preview(old, _dump(new_data, old), notes)


def _override(name: str, target: str, old: str, data: dict) -> PatchPreview:
    ov = data.get("overrides") or {}
    if isinstance(ov.get(name), dict):
        return PatchPreview(supported=False, notes=[f"overrides already has a nested rule for {name}: edit it by hand"])
    if _sections_with(data, name):
        return PatchPreview(supported=False, notes=[f"{name} is a direct dependency: npm rejects an override that conflicts with it; use an upgrade"])
    new_data = json.loads(json.dumps(data))
    new_data.setdefault("overrides", {})[name] = target
    notes = [f"overrides: {name} -> '{target}' (exact version; every dependent of {name} resolves to it)"]
    _roundtrip_note(old, data, notes)
    notes.append("package-lock.json will be regenerated when the plan is applied (not shown in this preview)")
    return _manifest_preview(old, _dump(new_data, old), notes)


def _remove(name: str, old: str, data: dict) -> PatchPreview:
    secs = _sections_with(data, name)
    if not secs:
        return PatchPreview(supported=False, notes=[f"{name} is not declared in package.json: it arrives through another dependency. "
                                                    "Remove or replace the parent dependency instead (escalate for a human decision)"])
    new_data = json.loads(json.dumps(data))
    notes = []
    for s in secs:
        del new_data[s][name]
        notes.append(f"{s}: removed {name}")
    _roundtrip_note(old, data, notes)
    notes.append("package-lock.json will be regenerated when the plan is applied; first-party code that imports it must be changed by hand")
    return _manifest_preview(old, _dump(new_data, old), notes)


def _revert(finding: dict, tree: Path, base_tree: Path | None, old: str | None, data: dict | None) -> PatchPreview:
    if base_tree is None:
        return PatchPreview(supported=False, notes=["no base tree is available, so the change cannot be reverted automatically"])
    comp = (finding.get("component") or "").strip()
    name = _package_name(finding)
    base_text = _read(base_tree, "package.json")
    if name and data is not None and old is not None and base_text is not None and (_sections_with(data, name) or NAME_VER.match(comp)):
        base = json.loads(base_text)
        new_data = json.loads(json.dumps(data))
        notes, changed = [], False
        for s in _sections_with(data, name):
            if name in (base.get(s) or {}):
                if new_data[s][name] != base[s][name]:
                    notes.append(f"{s}: {name} '{new_data[s][name]}' -> '{base[s][name]}' (base value)")
                    new_data[s][name] = base[s][name]
                    changed = True
            else:
                del new_data[s][name]
                notes.append(f"{s}: removed {name} (it was not present on base)")
                changed = True
        if changed:
            _roundtrip_note(old, data, notes)
            notes.append("package-lock.json will be regenerated when the plan is applied (not shown in this preview)")
            return _manifest_preview(old, _dump(new_data, old), notes)
        return PatchPreview(supported=False, notes=[f"{name} is not changed in package.json between base and head: it arrives through another "
                                                    "dependency, so there is no manifest line to revert"])
    rel = re.sub(r"^(\./)+", "", comp.replace("\\", "/")) if comp else ""  # keep a leading dot: ".npmrc" is a file name
    if rel and not rel.startswith("/") and ".." not in rel.split("/") and ("/" in rel or rel.startswith(".")):  # a file path such as .npmrc or a workflow
        head_text, base_file = _read(tree, rel), _read(base_tree, rel)
        if head_text is not None and base_file is not None:
            return PatchPreview(supported=True, diff=_unified(rel, head_text, base_file), files={rel: base_file}, lockfile="unchanged",
                                notes=[f"{rel} restored to its base content"])
        if head_text is not None and base_file is None:
            return PatchPreview(supported=True, diff=_unified(rel, head_text, ""), delete_files=[rel], lockfile="unchanged",
                                notes=[f"{rel} did not exist on base: it is deleted"])
    return PatchPreview(supported=False, notes=["this change type cannot be reverted automatically in v1; the human reverts the commit"])


def preview(candidate: dict, finding: dict, tree: Path, base_tree: Path | None = None) -> PatchPreview:
    """Pure: what would applying `candidate` change in `tree` (the PR-head project copy)? Never writes."""
    ctype, target = candidate["type"], candidate.get("target")
    if ctype in ("pin_action_sha", "pin_image_digest"):
        what = "tag -> commit SHA" if ctype == "pin_action_sha" else "image tag -> digest"
        return PatchPreview(supported=False, notes=[f"recommend-only in v1: resolving {what} needs a networked lookup that is not part of the preview. "
                                                    "The reviewer pins it by hand or via the vendor tool."])
    if ctype == "escalate":
        return PatchPreview(supported=False, lockfile="unchanged", notes=["no change is made: the finding is handed to a security reviewer"])
    old = _read(tree, "package.json")
    data = json.loads(old) if old else None
    name = _package_name(finding)
    if ctype == "revert_change":
        return _revert(finding, tree, base_tree, old, data)
    if old is None or data is None:
        return PatchPreview(supported=False, notes=["no package.json in the project tree"])
    if not name:
        return PatchPreview(supported=False, notes=["cannot tell which package this finding is about"])
    if ctype == "upgrade_to_fixed" and target:
        return _upgrade(name, target, old, data)
    if ctype == "override_transitive" and target:
        return _override(name, target, old, data)
    if ctype == "remove_package":
        return _remove(name, old, data)
    return PatchPreview(supported=False, notes=[f"unsupported candidate type {ctype}"])
