"""Deterministic referee for fix proposals (constitution C1, C5, C10, C10b).

Facts are settled here, never by an LLM:
  C10   a fix must equal one of the candidates generated by fixrank.generate (no invented version, type or finding)
  C10b  a hard-signal finding (one with a floor) can only get remove / revert / escalate (or pin for a CI action):
        it is never "fixed" by an upgrade, and no fix can lower its floor
  C1    the proposer's rationale may only mention versions and advisory ids that appear in the evidence it cites
  C5    no pasted untrusted content in a rationale
"""
from __future__ import annotations

from guardian.agents.constitution import ADVISORY_ID, NAME_VERSION
from guardian.scoring.contextual.fixrank import validate_proposed
from guardian.store.evidence import EvidenceStore

MAX_RATIONALE = 600
HARD_DEFAULT = {"remove_package", "revert_change", "escalate"}
HARD_BY_TYPE = {
    "action_sha_to_tag": {"pin_action_sha", "revert_change", "escalate"},
    "history_rewrite": {"escalate"},
}


class RefereeError(ValueError):
    """The message is shown to the proposing agent (or the user) so it can correct the action."""


def is_hard_signal(finding: dict) -> bool:
    return bool(finding.get("floor"))


def allowed_types(finding: dict) -> set[str] | None:
    """None = no restriction beyond 'must be a generated candidate'."""
    if not is_hard_signal(finding):
        return None
    kind = finding["id"].split(":", 1)[0] if finding.get("kind") == "supply_chain" else None
    return HARD_BY_TYPE.get(kind or "", HARD_DEFAULT)


def check_proposal(finding: dict | None, candidates: list[dict], ctype: str, target: str | None) -> dict:
    """Return the matching generated candidate, or raise RefereeError with the reason."""
    if finding is None:
        raise RefereeError("C10: unknown finding id. Use list_priority_findings to see the real ids.")
    ok, why = validate_proposed({"finding": finding["id"], "type": ctype, "target": target}, candidates,
                                {c["target"] for c in candidates if c.get("target")} or None)
    if not ok:
        raise RefereeError(f"C10: {why}. Valid candidates: " + ", ".join(f"{c['type']}@{c.get('target')}" for c in candidates))
    allowed = allowed_types(finding)
    if allowed is not None and ctype not in allowed:
        raise RefereeError(f"C10b: {finding['id']} is a hard signal ({finding['floor']}); only {sorted(allowed)} are allowed, "
                           f"not '{ctype}'. A hard signal is never fixed by an upgrade and its floor cannot be lowered.")
    return next(c for c in candidates if c["type"] == ctype and c.get("target") == target)


def check_claim(text: str, evidence_ids: list[str], store: EvidenceStore) -> None:
    """C1 / C5 for the proposer's rationale. Raises RefereeError."""
    if not evidence_ids:
        raise RefereeError("C1: a recommendation must cite evidence ids returned by tools.")
    missing = [i for i in evidence_ids if not store.exists(i)]
    if missing:
        raise RefereeError(f"C1: unknown evidence ids {missing}. Cite only ids returned by tools.")
    if len(text) > MAX_RATIONALE:
        raise RefereeError(f"rationale is {len(text)} characters; the limit is {MAX_RATIONALE}.")
    if "<untrusted-data" in text.lower():
        raise RefereeError("C5: do not paste untrusted content into a rationale; cite its evidence id.")
    cited = "\n".join(store.content(i) for i in evidence_ids).lower()
    for name, ver in NAME_VERSION.findall(text.lower()):
        ver = ver.rstrip(".-+")  # the shared regex swallows a sentence-ending period ("foo@1.2.4.")
        if f"{name}@{ver}" not in cited and not (name in cited and ver in cited):
            raise RefereeError(f"C1: '{name}@{ver}' does not appear in the cited evidence.")
    for adv in ADVISORY_ID.findall(text):
        if adv.lower() not in cited:
            raise RefereeError(f"C1: advisory '{adv}' does not appear in the cited evidence.")
